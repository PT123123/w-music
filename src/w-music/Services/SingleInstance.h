#pragma once

namespace wm::app
{
    /// 单实例：创建（或打开）命名互斥量。返回 true 表示本进程是第一个实例，
    /// 应当正常启动；返回 false 表示已有实例在跑，调用方应通知它并退出。
    /// 互斥量句柄在进程存续期间保持打开，进程退出时由系统释放。
    bool AcquireSingleInstance();

    /// 向已运行实例的托盘消息窗口投递"显示主窗口"消息。
    /// 托盘窗口在主窗口 Loaded 后才创建，所以这里会短暂重试；
    /// 找不到时静默返回（调用方照常退出即可，先启动的窗口马上就会出现）。
    void SignalExistingInstance();

    /// 第二实例的"交接"尝试，按旧实例的 exe 路径分流：
    /// - 同一个 exe（双击第二次）或认不出对方：走 SignalExistingInstance 唤到
    ///   前台，返回 false，调用方应退出；
    /// - 旧实例是另一个 exe（部署新版本后启动的典型场景）：投递
    ///   WM_TRAY_GRACEFUL_EXIT 请它走托盘"退出"的清理路径，等它退干净
    ///   （最多 6 秒）后把互斥量所有权接过来，返回 true，调用方正常启动；
    ///   等不到就退回上一条，绝不并行双开、也绝不杀进程。
    /// 0.1.21 及更早的旧版本不认识退出消息，只能等超时后退回唤到前台——
    /// 0.1.22 起的所有版本之间交接都是全自动的。
    bool TakeOverFromExistingInstance();
}
